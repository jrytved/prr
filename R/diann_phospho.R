#' Combine site-level and global parquet reports appropriately
#' @param site_parquet An object containing the site-level parquet report output by dia-nn.
#' @param full_parquet An object containing the full (report.parquet) output by dia-nn.
#' @return A data frame containing the joined site-level report (by precursor lib index and auxillary columns)
#' @export
#'
join_site_report <-function(site_parquet, full_parquet, join_by = c("Sample.ID", "Replicate.ID")){

    join_by = c(join_by, "Precursor.Lib.Index")

    dplyr::left_join(
      site.report, full_parquet,
      by=c("Precursor.Lib.Index", "Sample.ID", "Replicate.ID")
    )

}


#' Helper function for plot_phosphosites
retrieve_seq <- function(uniprot_acc, sequences){
  
  #' Retrieve FASTA sequence from table
  #' Table has minimal columns 'accession' and 'sequence'
  
  
  seq_list <- sequences %>%
  filter(accession == uniprot_acc)%>%
  pull(sequence)

  if (length(seq_list) != 1){
    stop(glue::glue("{length(seq_list)} sequences were returned. Expecting one."))
  }
  
  seq <- seq_list[[1]]
  
  return(seq)
  
}

#' Helper function for plot_phosphosites
retrieve_phosphosites <- function(uniprot_acc, site.table){
  
  #' Retrieve phosphosites from site table
  #' Returns table with (Protein, Residue, Site, Sample.ID)
  
  table <- site.table %>%
    filter(Protein == uniprot_acc)%>%
    distinct(Protein, Residue, Site, Sample.ID)
  
  return(table)
}

#'Plot phosphosites in an aesthetically pleasing way
#' @param id A uniprot identifier
#' @param sequences A dataframe of sequences (columns accession and sequence)
#' @param site.table A dataframe of phosphosites (columns named Protein, Residue, Site, Sample.Id)
#' @param conversion Conversion table (generated by other script)
#' @export
plot_phosphosites <- function(id, sequences, site.table, conversion,
                              residues_per_row = 50, crop = FALSE, pad = 50){
  
  sequence <- retrieve_seq(id, sequences)
  phosphosites <- retrieve_phosphosites(id, site.table)
  
  min_site_idx <- min(phosphosites$Site)
  max_site_idx <- max(phosphosites$Site)
  
  n.sites <- phosphosites %>%
    distinct(Sample.ID, Site, Residue) %>%
    nrow()
  
  n.unique.sites <- phosphosites %>%
    distinct(Site, Residue) %>%
    nrow()
  
  msg_str <- glue::glue("Fetched {n.sites} sites ({n.unique.sites} unique)")
  message(msg_str)
  
  msg_str <- glue::glue("Site index range [min:max]: [{min_site_idx}:{max_site_idx}]")
  message(msg_str)
  
  
  # Prepare sequences
  seq_chars <- strsplit(as.character(sequence), "")[[1]]
  seq_length <- length(seq_chars)
  
  if (max_site_idx > seq_length) {
    stop(glue::glue("Max site index ({max_site_idx}) exceeds sequence ",
                    "length ({seq_length}) for {id}"))
  }
  
  # Site report for plotting
  sites <- phosphosites %>%
    distinct(Sample.ID, Site, Residue) %>%
    arrange(Site, Sample.ID) %>%
    group_by(Site) %>%
    mutate(stack = row_number()) %>%
    ungroup()
  
  # Are there any mismatches between sequences and passed phosphosite?
  mismatches <- sites %>%
    distinct(Site, Residue) %>%
    mutate(seq_aa = seq_chars[Site]) %>%
    filter(Residue != seq_aa)
  
  if (nrow(mismatches) > 0) {
    warning(glue::glue(
      "{nrow(mismatches)} site(s) where Residue does not match the sequence: ",
      "{paste0(mismatches$Residue, mismatches$Site, '(seq: ', mismatches$seq_aa, ')', collapse = ', ')}"
    ))
  }
  
  # ---- Plotting range ------------------------------------------------------
  if (!crop) {
    # Show the entire sequence
    plot_start <- 1
    plot_end   <- seq_length
  } else if (min_site_idx == max_site_idx) {
    # Single site: pad on both sides, clamped to the sequence bounds
    plot_start <- max(1, min_site_idx - pad)
    plot_end   <- min(seq_length, max_site_idx + pad)
    message(glue::glue("Single site; padding by {pad} residues: [{plot_start}:{plot_end}]"))
  } else {
    # Crop to the observed site range
    plot_start <- min_site_idx
    plot_end   <- max_site_idx
  }
  
  # ---- Layout --------------------------------------------------------------
  label_step <- 0.6                                   # vertical spacing of sample labels
  max_stack  <- max(sites$stack)
  row_height <- max_stack * label_step + 1.9          # room for box, labels, position numbers
  n_per_row  <- min(residues_per_row, plot_end - plot_start + 1)
  
  seq_df <- tibble::tibble(pos = plot_start:plot_end) %>%
    mutate(
      aa       = seq_chars[pos],
      occupied = pos %in% sites$Site,
      offset   = pos - plot_start,
      x        = offset %% n_per_row,
      row      = offset %/% n_per_row,
      y        = -row * row_height
    )
  
  row_starts <- seq_df %>% filter(x == 0)
  
  label_df <- sites %>%
    left_join(seq_df %>% select(pos, x, y), by = c("Site" = "pos")) %>%
    mutate(label_y = y + 0.35 + stack * label_step)
  
  # Get metadata for title
  metadata <- conversion %>%
    filter(UniProt_Accession == id) %>%
    as.list()
  
  rec_name <- metadata$Recommended_Protein_Name
  gene_symbol <- metadata$Gene_Symbol
  
  plot_title <- glue::glue("{rec_name}")
  
  plot_subtitle <- glue::glue("{id} | {gene_symbol} | residues {plot_start}\u2013{plot_end} | {n.sites} sites  | ({n.unique.sites} unique)")
  
  # ---- Plot ----------------------------------------------------------------
  p <- ggplot() +
    # residue boxes
    geom_tile(data = seq_df,
              aes(x = x, y = y, fill = occupied),
              width = 0.9, height = 0.9,
              colour = "grey40", linewidth = 0.3) +
    # one-letter amino acid codes
    geom_text(data = seq_df,
              aes(x = x, y = y, label = aa),
              size = 3.5, fontface = "bold") +
    # position number below occupied sites
    geom_text(data = seq_df %>% filter(occupied),
              aes(x = x, y = y - 0.75, label = pos),
              size = 2.3, colour = "grey30") +
    # position of first residue in each row
    geom_text(data = row_starts,
              aes(x = -0.7, y = y, label = pos),
              hjust = 1, size = 2.8, colour = "grey30") +
    # sample IDs stacked above occupied sites
    geom_text(data = label_df,
              aes(x = x, y = label_y, label = Sample.ID),
              size = 2.5) +
    scale_fill_manual(values = c(`FALSE` = "grey95", `TRUE` = "#F4A261"),
                      guide = "none") +
    scale_x_continuous(expand = expansion(add = c(2, 1))) +
    coord_equal(clip = "off") +
    labs(
      title    = plot_title,
      subtitle = plot_subtitle
    ) +
    theme_void() +
    theme(
      plot.title    = element_text(face = "bold"),
      plot.subtitle = element_text(colour = "grey30"),
      plot.margin   = margin(10, 10, 10, 10)
    )
  
  return(p)
}